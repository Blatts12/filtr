# Runs every benchmark under test/benchmark and writes the combined output to
# test/benchmark/results.md.
# mix run test/benchmark/run_all.exs            # run everything
# mix run test/benchmark/run_all.exs list date  # only suites matching "list" or "date"

bench_dir = __DIR__

# Benchee options shared by every suite - the single place to tune the whole run.
# Edit the defaults here, or override any of them per run, e.g. `BENCH_TIME=1 mix bench`.
# They're handed to each suite through env vars that test/benchmark/bench.exs reads.
benchee_config = [
  warmup: System.get_env("BENCH_WARMUP", "2"),
  time: System.get_env("BENCH_TIME", "10"),
  memory_time: System.get_env("BENCH_MEMORY_TIME", "10")
]

bench_env =
  Enum.map(benchee_config, fn {key, value} ->
    {"BENCH_#{String.upcase(to_string(key))}", value}
  end)

benchmarks = [
  {"Collect errors", "collect_errors.exs"},
  {"Types: string", "types/string.exs"},
  {"Types: integer", "types/integer.exs"},
  {"Types: float", "types/float.exs"},
  {"Types: boolean", "types/boolean.exs"},
  {"Types: date", "types/date.exs"},
  {"Types: datetime", "types/datetime.exs"},
  {"Types: list", "types/list.exs"},
  {"Nested maps", "nesting.exs"},
  {"Lists of nested schemas", "lists.exs"},
  {"All types at once", "all_types.exs"},
  {"Plugin dispatch", "plugins.exs"},
  {"Plugin registration", "plugin_registration.exs"}
]

filters = System.argv()

selected =
  Enum.filter(benchmarks, fn {title, path} ->
    filters == [] or
      Enum.any?(filters, fn f ->
        String.contains?(path, f) or String.contains?(String.downcase(title), String.downcase(f))
      end)
  end)

# Drop ANSI color/cursor sequences and carriage returns that Benchee's console
# formatter leaves behind, so the captured text reads cleanly in Markdown.
clean = fn text ->
  text
  |> String.replace(~r/\e\[[0-9;]*[a-zA-Z]/, "")
  |> String.replace("\r", "")
  |> String.trim_trailing()
end

# Benchee reprints the same OS/CPU + configuration block before every suite. Split
# it off the front so we can show it once at the top instead of in every section.
env_marker = "Excluding outliers: false"

split_env = fn output ->
  case String.split(output, env_marker, parts: 2) do
    [env, body] -> {String.trim(env) <> env_marker, String.trim_leading(body)}
    [_] -> {nil, output}
  end
end

results =
  Enum.map(selected, fn {title, path} ->
    IO.puts("Running #{title} (#{path}) ...")

    {output, status} =
      System.cmd("mix", ["run", Path.join(bench_dir, path)], stderr_to_stdout: true, env: bench_env)

    {env, body} = split_env.(clean.(output))
    %{title: title, path: path, status: status, env: env, body: body}
  end)

# The block is identical for every suite, so keep the first one and drop the
# per-suite "Estimated total run time" line that would otherwise be misleading here.
env_block =
  results
  |> Enum.find_value(& &1.env)
  |> case do
    nil -> nil
    env -> String.replace(env, ~r/\nEstimated total run time:.*/, "")
  end

sections =
  Enum.map(results, fn %{title: title, path: path, status: status, body: body} ->
    note = if status == 0, do: "", else: "\n> ⚠️ exited with status #{status}\n"

    """
    ## #{title}

    `benchmark/#{path}`
    #{note}
    ```
    #{body}
    ```
    """
  end)

header = """
# Filtr benchmark results

Generated by `mix run benchmark/run_all.exs` on #{DateTime.to_string(DateTime.utc_now())}.
"""

env_section = if env_block, do: "## Environment\n\n```\n#{env_block}\n```\n", else: ""

results_path = Path.join(bench_dir, "results.md")
File.write!(results_path, Enum.join([header, env_section | sections], "\n"))

IO.puts("\nWrote #{results_path}")
